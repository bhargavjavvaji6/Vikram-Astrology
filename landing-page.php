        document.getElementById('lead-form').addEventListener('submit', function (e) {
            e.preventDefault();

            var form = e.target;
            var submitBtn = document.getElementById('lead-submit-btn');
            var successMsg = document.getElementById('form-success-msg');
            var errorMsg = document.getElementById('form-error-msg');

            successMsg.style.display = 'none';
            errorMsg.style.display = 'none';
            submitBtn.textContent = 'Sending...';
            form.classList.add('as_form_loading');

            var formData = new FormData(form);

            fetch(form.action, {
                method: 'POST',
                body: formData,
                headers: { 'Accept': 'application/json' }
            })
                .then(function (response) {
                    if (response.ok) {
                        form.reset();
                        form.style.display = 'none';
                        successMsg.style.display = 'block';
                    } else {
                        throw new Error('Submission failed');
                    }
                })
                .catch(function () {
                    errorMsg.style.display = 'block';
                    submitBtn.textContent = 'Book Your Private Reading';
                    form.classList.remove('as_form_loading');
                });
        });
